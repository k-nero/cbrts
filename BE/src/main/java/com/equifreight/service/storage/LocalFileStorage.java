package com.equifreight.service.storage;

import com.equifreight.exception.StorageException;
import java.io.IOException;
import java.io.InputStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import org.springframework.core.io.InputStreamSource;

/**
 * {@link FileStorage} in a directory, for running without Docker and for tests. Keys map to paths
 * under the root ({@code files/2026/10/<uuid>}). Not for production: one machine, no replication.
 */
public class LocalFileStorage implements FileStorage {

    private final Path root;

    public LocalFileStorage(Path root) {
        this.root = root.toAbsolutePath().normalize();
    }

    /**
     * Writes to a temporary file first and renames it into place, so a crash never leaves a partial
     * file under a real key. The move has no options on purpose: ATOMIC_MOVE would silently replace
     * an existing file on Linux and macOS, while a plain move refuses to, which keeps keys write-once.
     */
    @Override
    public void put(String key, InputStreamSource content, long size, String contentType) {
        Path target = resolve(key);
        Path temp = null;
        try {
            Files.createDirectories(target.getParent());
            temp = Files.createTempFile(target.getParent(), ".upload-", ".tmp");
            long written;
            try (InputStream in = content.getInputStream()) {
                written = Files.copy(in, temp, StandardCopyOption.REPLACE_EXISTING);
            }
            if (written != size) {
                throw new IOException("Expected " + size + " bytes, got " + written);
            }
            Files.move(temp, target);
            temp = null;
        } catch (IOException e) {
            throw new StorageException("Could not store the file", e);
        } finally {
            if (temp != null) {
                try {
                    Files.deleteIfExists(temp);
                } catch (IOException ignored) {
                    // Only a stray temp file, named so it never collides with a key.
                }
            }
        }
    }

    @Override
    public InputStream open(String key) {
        try {
            // A missing file is also an error here: the files row says it exists.
            return Files.newInputStream(resolve(key));
        } catch (IOException e) {
            throw new StorageException("Could not read the file", e);
        }
    }

    @Override
    public void delete(String key) {
        try {
            Files.deleteIfExists(resolve(key));
        } catch (IOException e) {
            throw new StorageException("Could not delete the file", e);
        }
    }

    /**
     * Keys are generated by FileService, but a key that escapes the root is refused all the same.
     */
    private Path resolve(String key) {
        Path path = root.resolve(key).normalize();
        if (!path.startsWith(root) || path.equals(root)) {
            throw new IllegalArgumentException("Invalid storage key: " + key);
        }
        return path;
    }
}
